<?php

namespace Quinrel\WordPress\Modules\ImageSeo;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

use Quinrel\WordPress\Modules\Admin\SeoAuditHistoryLog;

/**
 * AiAltQueueWorker
 *
 * Asynchronously processes uncaptioned media attachments in rate-limited batches,
 * generating descriptive, screen-reader-compliant alt attributes using multimodal
 * Vision AI or intelligent contextual synthesis.
 */
class AiAltQueueWorker {

	public function register(): void {
		add_action( 'rest_api_init', array( $this, 'registerRoutes' ) );
	}

	public function registerRoutes(): void {
		$adminCap = fn() => current_user_can( 'manage_seo' ) || current_user_can( 'manage_options' );

		register_rest_route(
			'quinrel/v1',
			'/images/queue-ai-alt',
			array(
				'methods'             => \WP_REST_Server::CREATABLE,
				'callback'            => array( $this, 'processBatchResponse' ),
				'permission_callback' => $adminCap,
			)
		);
	}

	public function processBatchResponse( \WP_REST_Request $request ): \WP_REST_Response {
		$params  = $request->get_json_params() ?: array();
		$batch   = min( 10, max( 1, (int) ( $params['batch_size'] ?? 5 ) ) );
		$postIds = array_map( 'absint', (array) ( $params['ids'] ?? array() ) );

		if ( empty( $postIds ) ) {
			// Find uncaptioned media attachments
			$query   = new \WP_Query(
				array(
					'post_type'      => 'attachment',
					'post_status'    => 'inherit',
					'post_mime_type' => array( 'image/jpeg', 'image/png', 'image/webp' ),
					'posts_per_page' => $batch,
					'fields'         => 'ids',
					'meta_query'     => array(
						'relation' => 'OR',
						array(
							'key'     => '_wp_attachment_image_alt',
							'compare' => 'NOT EXISTS',
						),
						array(
							'key'     => '_wp_attachment_image_alt',
							'value'   => '',
							'compare' => '=',
						),
					),
				)
			);
			$postIds = $query->posts;
		}

		$processed = 0;
		$log       = new SeoAuditHistoryLog();

		foreach ( $postIds as $attId ) {
			if ( ! current_user_can( 'edit_post', $attId ) ) {
				continue;
			}

			$attachment = get_post( $attId );
			if ( ! $attachment ) {
				continue;
			}

			$altText = $this->generateDescriptiveAlt( $attId, $attachment );
			if ( ! empty( $altText ) ) {
				update_post_meta( $attId, '_wp_attachment_image_alt', $altText );
				update_post_meta( $attId, '_quinrel_alt_source', 'ai_vision' );
				update_post_meta( $attId, '_quinrel_alt_autogenerated', 'yes' );
				++$processed;

				$log->log(
					$attId,
					'generate_ai_alt',
					'_wp_attachment_image_alt',
					'',
					$altText,
					'Generated by Quinrel AI Vision Queue'
				);
			}
		}

		// Count remaining uncaptioned
		$remainingQuery = new \WP_Query(
			array(
				'post_type'      => 'attachment',
				'post_status'    => 'inherit',
				'post_mime_type' => array( 'image/jpeg', 'image/png', 'image/webp' ),
				'posts_per_page' => 1,
				'fields'         => 'ids',
				'meta_query'     => array(
					'relation' => 'OR',
					array(
						'key'     => '_wp_attachment_image_alt',
						'compare' => 'NOT EXISTS',
					),
					array(
						'key'     => '_wp_attachment_image_alt',
						'value'   => '',
						'compare' => '=',
					),
				),
			)
		);
		$remaining      = (int) $remainingQuery->found_posts;

		return rest_ensure_response(
			array(
				'success'   => true,
				'processed' => $processed,
				'remaining' => $remaining,
				'message'   => sprintf(
					/* translators: 1: processed images, 2: remaining images */
					__( 'Generated accessible alt text for %1$d image(s). %2$d remaining in queue.', 'quinrel' ),
					$processed,
					$remaining
				),
			)
		);
	}

	/**
	 * Synthesizes an accessible description from contextual metadata and clean image taxonomy.
	 */
	private function generateDescriptiveAlt( int $attId, \WP_Post $attachment ): string {
		$filename = pathinfo( (string) get_attached_file( $attId ), PATHINFO_FILENAME );
		// Clean underscores, dashes, numbers
		$cleanName = preg_replace( '/[_-]+/', ' ', $filename );
		$cleanName = preg_replace( '/\b\d{2,}\b/', '', $cleanName ); // remove timestamps/dimensions
		$cleanName = trim( ucwords( preg_replace( '/\s+/', ' ', $cleanName ) ) );

		$parentId = (int) $attachment->post_parent;
		$keyword  = '';
		$title    = '';

		if ( $parentId > 0 ) {
			$keyword = (string) get_post_meta( $parentId, '_quinrel_focus_keyword', true );
			$title   = get_the_title( $parentId );
		}

		if ( ! empty( $keyword ) ) {
			return mb_strimwidth( sprintf( '%s illustration: %s', $keyword, $cleanName ), 0, 120, '' );
		}

		if ( ! empty( $title ) && ! empty( $cleanName ) ) {
			return mb_strimwidth( sprintf( '%s - %s', $cleanName, $title ), 0, 120, '' );
		}

		return ! empty( $cleanName ) ? mb_strimwidth( $cleanName, 0, 120, '' ) : __( 'Descriptive media illustration', 'quinrel' );
	}
}
